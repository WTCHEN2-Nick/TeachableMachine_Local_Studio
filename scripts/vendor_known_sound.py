"""Vendor the App Builder Known Sound pack into mcu_toolkit/apps/known_sound/ (GCC edition).

Run by the maintainer through ``vendor_mcu_toolkit.py known-sound``; students never run it.

Two kinds of output:

* the verified C -- ``frontend/`` (the portable YAMNet 96x64 log-mel the host tests compile
  bit-for-bit against TensorFlow) and ``device/`` (DMIC + LPPDMA capture, and the one
  ``BoardConfig.h`` that decides which microphone pins exist on which board) -- copied byte for
  byte, because the point of that code is that the desktop and the board run the same
  translation unit;
* ``main.cpp.in``, a *static* token template built once from the App Builder's
  ``known_sound_runtime._MAIN_TEMPLATE`` so the Studio needs neither jinja2 nor the App Builder
  at deploy time.

Every App Builder placeholder that the Studio does not fill in at deploy time is resolved here:
``tm_local.mcu.codegen.render_tokens`` refuses a template carrying any leftover ``@@TOKEN@@``, so
the only ones allowed to survive are the seven in :data:`DEPLOY_TOKENS`.

The one behavioural change from upstream is the threshold. The App Builder compiles a single
``KNOWN_SOUND_THRESHOLD`` for every class; ``known_sound`` is multi-label, each class carries its
own independent sigmoid score, and the Studio lets the student tune one threshold per class -- so
the scalar becomes ``s_afThreshold[]`` and the single pre-computed output code becomes one code
per class. Every anchor below is checked ``count == 1``: a silently skipped edit would ship
firmware that looks right and thresholds the wrong classes.
"""
