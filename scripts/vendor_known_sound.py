def _fail(message: str) -> None:
    raise SystemExit(f"vendor_known_sound: {message}")


def _replace_once(text: str, old: str, new: str, label: str) -> str:
    found = text.count(old)
    if found != 1:
        _fail(f"known_sound template anchor {label!r} found {found} times")
    return text.replace(old, new)


def _import_known_sound_runtime(app_builder_root: Path) -> ModuleType:
    """Import the App Builder runtime module without writing into its (read-only) tree."""
    module_path = app_builder_root / "tools" / "known_sound_runtime.py"
    if not module_path.is_file():
        _fail(f"App Builder Known Sound runtime not found at {module_path}")
    if str(app_builder_root) not in sys.path:
        sys.path.insert(0, str(app_builder_root))
    previous = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        from tools import known_sound_runtime  # App Builder module (read-only use)
    finally:
        sys.dont_write_bytecode = previous
    marker = getattr(known_sound_runtime, "KNOWN_SOUND_RUNTIME_MARKER", "")
    if marker != EXPECTED_RUNTIME_MARKER:
        _fail(
            f"App Builder runtime marker is {marker!r}, expected {EXPECTED_RUNTIME_MARKER!r}; "
            f"this pack claims App Builder v{APP_BUILDER_VERSION} -- re-check the anchors below "
            "before bumping it"
        )
    return known_sound_runtime


def build_main_template(runtime: ModuleType) -> str:
    """Turn ``_MAIN_TEMPLATE`` into the Studio's static, seven-token ``main.cpp.in``."""
    text = runtime._MAIN_TEMPLATE
    text = _replace_once(
        text, "@@MARKER@@", "TEACHABLE_MACHINE_LOCAL_STUDIO_KNOWN_SOUND_RUNTIME_V1", "marker"
    )
    text = _replace_once(text, "@@MODEL_SOURCE_INCLUDES@@", "", "includes")
    text = _replace_once(text, "@@MODEL_SOURCE_DECLS@@", MODEL_DECLS, "decls")
    text = _replace_once(text, "@@MODEL_SOURCE_LOADER@@", "", "loader")
    # Internal flash only: the Studio never deploys a model from the SD card, so the SD loader
    # and its FatFs includes must not reach the vendored template at all.
    text = _replace_once(text, "@@MODEL_INIT@@", runtime._MODEL_INIT_INTERNAL, "init")
    text = _replace_once(
        text, "@@MODEL_SIZE_EXPR@@", "(unsigned)arm::app::nn::GetModelLen()", "size"
    )

    # One threshold per class instead of one for the whole model.
    text = _replace_once(
        text, "#define KNOWN_SOUND_THRESHOLD    @@THRESHOLD@@f\n", "", "threshold define"
    )
    text = _replace_once(text, LABELS_BLOCK, LABELS_BLOCK + THRESHOLD_ARRAY, "labels")
    text = _replace_once(text, THRESHOLD_CODE_OLD, THRESHOLD_CODE_NEW, "threshold code")
    text = _replace_once(text, THRESHOLD_PRINT_OLD, THRESHOLD_PRINT_NEW, "threshold print")
    text = _replace_once(
        text,
        '(psOutput->data.int8[i] >= iThresholdCode) ? "*" : " "',
        '(psOutput->data.int8[i] >= aiThresholdCode[i]) ? "*" : " "',
        "marker star",
    )

    # Round half to EVEN, not half away from zero. TFLite's own quantiser, the Studio's
    # Preview runner and the host golden all use half-even (numpy's rint / C's lrintf under
    # the default FE_TONEAREST); lroundf rounds .5 away from zero, so every log-mel value
    # landing exactly on a half-code came out one LSB higher on the board than in the golden
    # the host tests compare against.
    text = _replace_once(
        text,
        "int iCode = (int)lroundf(s_afPatch[i] / fInScale) + iInZero;",
        "int iCode = (int)lrintf(s_afPatch[i] / fInScale) + iInZero;",
        "patch quantisation rounding",
    )

    for token in DEPLOY_TOKENS:
        if token not in text:
            _fail(f"token {token} missing after transformation")
    for forbidden in ("@@THRESHOLD@@", "@@MODEL_", "KNOWN_SOUND_THRESHOLD", "lroundf"):
        if forbidden in text:
            _fail(f"{forbidden} still present after transformation")
    # The const-correct declaration must be the only one: a second, non-const declaration
    # anywhere in the file would put the ODR violation straight back.
    if text.count("extern const uint8_t *GetModelPointer();") != 1:
        _fail("expected exactly one const-qualified GetModelPointer() declaration")
    if re.search(r"extern\s+uint8_t\s*\*\s*GetModelPointer", text):
        _fail("a non-const GetModelPointer() declaration survived vendoring")
    # \b before `i` does not match inside `aiThresholdCode`, so this finds a surviving use of the
    # single shared threshold code without tripping over the per-class array that replaced it.
    if re.search(r"\biThresholdCode\b", text):
        _fail("the single shared iThresholdCode still has a use after transformation")
    # render_tokens() raises on ANY leftover token, so the surviving set must be exactly the seven
    # the deploy step knows how to fill in -- no more, and (checked above) no fewer.
    survivors = set(re.findall(r"@@[A-Z0-9_]+@@", text))
    if survivors != set(DEPLOY_TOKENS):
        _fail(f"unexpected tokens survived vendoring: {sorted(survivors - set(DEPLOY_TOKENS))}")
    return HEADER + text


def patch_harness(text: str) -> str:
    """Redirect the host build out of the vendored tree and make MSVC optional.

    Same discipline as the main.cpp.in anchors above: every replacement must hit exactly once,
    and the result is re-checked for the constructs the patches exist to remove.  A silently
    skipped edit here would put a generated build script and a DLL back inside ``mcu_toolkit/``,
    where the manifest test would blame the vendoring rather than this script.
    """
    for label, old, new in HARNESS_PATCHES:
        text = _replace_once(text, old, new, label)
    for required in ("def find_vcvars(", "def frontend(build_dir", "def _msvc_environment(",
                     "hashlib.sha256", "DEFAULT_BUILD_DIR", "TM_VCVARS64"):
        if required not in text:
            _fail(f"harness.py lacks {required!r} after patching")
    # "build.bat" and the write that produced it: the repository ships exactly two .bat files and
    # tests/test_distribution.py scans the whole tree, so a generated third one fails it wherever
    # it lands -- including under the git-ignored workspace/tmp/.
    for forbidden in ("build_host", "st_mtime_ns", "BUILD.mkdir", "cwd=str(BUILD)", "build.bat"):
        if forbidden in text:
            _fail(f"harness.py still contains {forbidden!r} after patching")
    return text


def redact_meta(path: Path, key_paths: tuple[tuple[str, ...], ...]) -> None:
    """Replace absolute maintainer paths inside a vendored ``*_meta.json`` with ``<redacted>``.

    The value is swapped in the raw text rather than by re-serialising the parsed document, and
    newlines are read and written untranslated, so every other byte of the App Builder's file
    survives: a reviewer diffing the vendored tree sees one changed value and nothing else.
    """
    raw = path.read_text(encoding="utf-8", newline="")
    data = json.loads(raw)
    for key_path in key_paths:
        node = data
        for key in key_path[:-1]:
            node = node.get(key) if isinstance(node, dict) else None
            if not isinstance(node, dict):
                _fail(f"{path.name}: no object at {'/'.join(key_path)}; upstream layout changed")
        value = node.get(key_path[-1])
        if not isinstance(value, str):
            _fail(f"{path.name}: {'/'.join(key_path)} is not a string; upstream layout changed")
        encoded = json.dumps(value)
        if raw.count(encoded) != 1:
            _fail(f"{path.name}: {'/'.join(key_path)} value found {raw.count(encoded)} times")
        raw = raw.replace(encoded, json.dumps(REDACTED))
    path.write_text(raw, encoding="utf-8", newline="")


def verify_no_private_paths(out: Path) -> None:
    """Fail the vendoring rather than ship a home directory inside the student zip."""
    for path in sorted(out.rglob("*")):
        if path.is_file() and path.suffix.lower() in TEXT_SUFFIXES:
            found = PRIVATE_PATH_RE.search(path.read_bytes())
            if found:
                _fail(f"{path} carries a developer path: {found.group().decode('latin-1')!r}")


def _patch_harness_file(path: Path) -> None:
    """Rewrite the copied harness in place, keeping the upstream file's line endings."""
    raw = path.read_bytes()
    newline = "\r\n" if b"\r\n" in raw else "\n"
    text = raw.decode("utf-8").replace("\r\n", "\n")
    path.write_text(patch_harness(text), encoding="utf-8", newline=newline)


def vendor_known_sound(app_builder_root: Path, dest_root: Path) -> None:
    known_sound_runtime = _import_known_sound_runtime(app_builder_root)
    main_text = build_main_template(known_sound_runtime)

    pack_src = app_builder_root / "known_sound"
    if not pack_src.is_dir():
        _fail(f"App Builder Known Sound pack not found at {pack_src}")

    out = dest_root / "apps" / "known_sound"
    if out.exists():
        shutil.rmtree(out)
    (out / "frontend").mkdir(parents=True)
    (out / "device").mkdir()
    for name in FRONTEND:
        shutil.copy2(pack_src / "frontend" / name, out / "frontend" / name)
    for name in DEVICE:
        shutil.copy2(pack_src / "device" / name, out / "device" / name)

    # Copied, not run, by this script: tests/test_known_sound_frontend_host.py drives the golden
    # vectors from the Studio's own suite, importing only harness.py.  The App Builder's own two
    # test modules are deliberately left behind (see HOST_TEST_FILES).
    host = out / "host_tests"
    host.mkdir()
    shutil.copytree(
        pack_src / "golden", host / "golden", ignore=shutil.ignore_patterns(*GOLDEN_EXCLUDE_DIRS)
    )
    for name, key_paths in META_REDACTIONS.items():
        redact_meta(host / "golden" / name, key_paths)
    for name in HOST_TEST_FILES:
        shutil.copy2(pack_src / "tests" / name, host / name)
    _patch_harness_file(host / "harness.py")
    for name in HOST_TOOL_FILES:
        source = pack_src / "tools" / name
        if source.is_file():
            shutil.copy2(source, host / name)

    (out / "main.cpp.in").write_text(main_text, encoding="utf-8", newline="\n")
    (out / "README.md").write_text(README, encoding="utf-8", newline="\n")
    verify_no_private_paths(out)
    print(f"[OK] known_sound: wrote {out / 'main.cpp.in'}")
